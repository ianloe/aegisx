export interface BoardPackData {
  generatedDate: string;
  organisationName: string;
  filterSummary: string;
  totalAssets: number;
  agentAssets: number;
  lifecycleCounts: Record<string, number>;
  autonomyCounts: Record<string, number>;
  averageFrameScore: number;
  aaefDistribution: Record<string, number>;
  totalCostSgd: number;
  measuredBenefitSgd: number;
  assumedOrEstimatedSgd: number;
  netBenefitSgd: number;
  roiPercent: number;
  valueAtRiskSgd: number;
  riskAdjustedRoiPercent: number;
  appetiteBreachCount: number;
  overdueActionsCount: number;
  topRisks: Array<{ code: string; title: string; assetCode: string; residualScore: number; breached: boolean }>;
  recentIncidents: Array<{ code: string; title: string; assetCode: string; severity: string; date: string }>;
}

function escapePdfText(text: string): string {
  return text
    .replace(/[^\x20-\x7E]/g, " ")
    .replace(/\\/g, "\\\\")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)");
}

function formatCompactCurrency(amount: number): string {
  const abs = Math.abs(amount);
  const sign = amount < 0 ? "-" : "";
  if (abs >= 1_000_000) return `${sign}SGD ${(abs / 1_000_000).toFixed(2)}M`;
  if (abs >= 1_000) return `${sign}SGD ${(abs / 1_000).toFixed(1)}k`;
  return `${sign}SGD ${abs.toFixed(0)}`;
}

/**
 * Draws a horizontal bar chart panel inside an A4 PDF page stream.
 */
function drawHorizontalBarChart(
  ops: string[],
  opts: {
    x: number;
    yTop: number;
    w: number;
    h: number;
    title: string;
    items: Array<{ label: string; value: number; displayValue?: string; rgb: string }>;
  },
) {
  const { x, yTop, w, h, title, items } = opts;
  const yBottom = yTop - h;

  // Card background & border
  ops.push("1 1 1 rg");
  ops.push(`${x} ${yBottom} ${w} ${h} re f`);
  ops.push("0.86 0.89 0.93 RG 0.7 w");
  ops.push(`${x} ${yBottom} ${w} ${h} re S`);

  // Card header strip
  ops.push("0.96 0.97 0.99 rg");
  ops.push(`${x} ${yTop - 22} ${w} 22 re f`);
  ops.push("0.118 0.227 0.373 rg");
  ops.push(`BT /F2 9 Tf ${x + 10} ${yTop - 15} Td (${escapePdfText(title)}) Tj ET`);

  const maxVal = Math.max(1, ...items.map((i) => Math.abs(i.value)));
  const labelW = 76;
  const valW = 48;
  const barMaxW = Math.max(30, w - labelW - valW - 22);
  const rowStep = (h - 32) / Math.max(1, items.length);

  items.forEach((item, idx) => {
    const rowY = yTop - 38 - idx * rowStep;
    const barW = Math.max(item.value === 0 ? 0 : 4, (Math.abs(item.value) / maxVal) * barMaxW);

    // Label
    ops.push("0.20 0.25 0.33 rg");
    ops.push(`BT /F1 8 Tf ${x + 10} ${rowY} Td (${escapePdfText(item.label.slice(0, 15))}) Tj ET`);

    // Track
    ops.push("0.94 0.95 0.97 rg");
    ops.push(`${x + 10 + labelW} ${rowY - 2} ${barMaxW} 9 re f`);

    // Bar
    if (barW > 0) {
      ops.push(`${item.rgb} rg`);
      ops.push(`${x + 10 + labelW} ${rowY - 2} ${barW.toFixed(1)} 9 re f`);
    }

    // Value text
    const valLabel = item.displayValue ?? String(item.value);
    ops.push("0.08 0.12 0.18 rg");
    ops.push(`BT /F2 8 Tf ${x + 14 + labelW + barMaxW} ${rowY} Td (${escapePdfText(valLabel)}) Tj ET`);
  });
}

function buildPageFooter(ops: string[], pageNum: number, totalPages: number) {
  ops.push("0.85 0.88 0.92 RG 0.6 w 36 46 m 559.28 46 l S");
  ops.push("0.38 0.43 0.50 rg");
  ops.push(
    "BT /F1 7.5 Tf 36 33 Td (FRAME and AAEF by Ian Loe, Tactics Solutions, licensed CC BY-NC 4.0. Generated by Aegis AI Governance Platform.) Tj ET",
  );
  ops.push(`BT /F2 7.5 Tf 515 33 Td (Page ${pageNum} of ${totalPages}) Tj ET`);
}

/**
 * Generates a print-ready, multi-page A4 (595.28 x 841.89 pt) PDF Board Pack
 * with KPI cards, vector charts, and formatted tables in British English.
 */
export function generateBoardPackPdfBuffer(data: BoardPackData): Buffer {
  // ---------------- PAGE 1: EXECUTIVE SUMMARY & CHARTS ----------------
  const p1: string[] = [];

  // Subtle page background header band
  p1.push("0.094 0.184 0.310 rg");
  p1.push("0 758 595.28 84 re f");
  // Accent stripe (#0072B2)
  p1.push("0.000 0.447 0.698 rg");
  p1.push("0 754 595.28 4 re f");

  p1.push("1 1 1 rg");
  p1.push("BT /F2 15 Tf 36 802 Td (AEGIS AI GOVERNANCE COMMAND CENTRE) Tj ET");
  p1.push("0.82 0.89 0.96 rg");
  p1.push("BT /F2 10 Tf 36 786 Td (EXECUTIVE & BOARD GOVERNANCE PACK) Tj ET");
  p1.push(
    `BT /F1 8.5 Tf 36 770 Td (${escapePdfText(
      `Organisation: ${data.organisationName}   |   Generated: ${data.generatedDate}   |   Scope: ${data.filterSummary}`,
    )}) Tj ET`,
  );

  // 4 KPI Summary Cards (yTop = 736, h = 66)
  const kpis = [
    {
      title: "AI PORTFOLIO",
      value: `${data.totalAssets} Assets`,
      sub: `${data.agentAssets} AAEF Agents`,
      accent: "0.000 0.447 0.698",
    },
    {
      title: "AVG FRAME MATURITY",
      value: `${data.averageFrameScore.toFixed(2)} / 4.00`,
      sub: "5-Dimension Envelope",
      accent: "0.000 0.620 0.451",
    },
    {
      title: "RISK-ADJUSTED ROI",
      value: `${data.riskAdjustedRoiPercent}%`,
      sub: `Headline ROI: ${data.roiPercent}%`,
      accent: "0.337 0.706 0.914",
    },
    {
      title: "APPETITE & ACTIONS",
      value: `${data.appetiteBreachCount} Breaches`,
      sub: `${data.overdueActionsCount} Overdue Actions`,
      accent: data.appetiteBreachCount > 0 ? "0.835 0.369 0.000" : "0.000 0.620 0.451",
    },
  ];

  const cardW = 124.8;
  const cardGap = 8;
  kpis.forEach((k, idx) => {
    const cx = 36 + idx * (cardW + cardGap);
    const cyBottom = 670;
    p1.push("0.98 0.99 1.00 rg");
    p1.push(`${cx} ${cyBottom} ${cardW} 66 re f`);
    p1.push("0.86 0.89 0.93 RG 0.7 w");
    p1.push(`${cx} ${cyBottom} ${cardW} 66 re S`);
    // Left accent bar
    p1.push(`${k.accent} rg`);
    p1.push(`${cx} ${cyBottom} 3.5 66 re f`);

    p1.push("0.40 0.45 0.52 rg");
    p1.push(`BT /F2 7.5 Tf ${cx + 10} ${cyBottom + 50} Td (${escapePdfText(k.title)}) Tj ET`);
    p1.push("0.07 0.11 0.18 rg");
    p1.push(`BT /F2 13 Tf ${cx + 10} ${cyBottom + 29} Td (${escapePdfText(k.value)}) Tj ET`);
    p1.push("0.35 0.40 0.48 rg");
    p1.push(`BT /F1 8 Tf ${cx + 10} ${cyBottom + 12} Td (${escapePdfText(k.sub)}) Tj ET`);
  });

  // FRAME Maturity Progress Strip (y = 636..656)
  p1.push("0.96 0.97 0.99 rg");
  p1.push("36 626 523.28 32 re f");
  p1.push("0.86 0.89 0.93 RG 0.7 w 36 626 523.28 32 re S");
  p1.push("0.118 0.227 0.373 rg");
  p1.push("BT /F2 8.5 Tf 46 645 Td (FRAME GOVERNANCE MATURITY PROGRESS) Tj ET");
  const framePct = Math.max(0, Math.min(1, data.averageFrameScore / 4));
  p1.push("0.88 0.91 0.95 rg 46 633 430 7 re f");
  p1.push("0.000 0.620 0.451 rg");
  p1.push(`46 633 ${(430 * framePct).toFixed(1)} 7 re f`);
  p1.push("0.10 0.14 0.20 rg");
  p1.push(`BT /F2 8.5 Tf 486 633 Td (${(framePct * 100).toFixed(0)}% of 4.0) Tj ET`);

  // Charts Grid (2x2)
  const chartW = 255.64;
  const chartH = 148;
  const leftX = 36;
  const rightX = 36 + chartW + 12;

  drawHorizontalBarChart(p1, {
    x: leftX,
    yTop: 612,
    w: chartW,
    h: chartH,
    title: "1. ASSETS BY LIFECYCLE STAGE",
    items: [
      { label: "Idea", value: data.lifecycleCounts.IDEA ?? 0, rgb: "0.45 0.52 0.60" },
      { label: "Pilot", value: data.lifecycleCounts.PILOT ?? 0, rgb: "0.337 0.706 0.914" },
      { label: "Production", value: data.lifecycleCounts.PRODUCTION ?? 0, rgb: "0.000 0.447 0.698" },
      { label: "Retired", value: data.lifecycleCounts.RETIRED ?? 0, rgb: "0.65 0.70 0.76" },
    ],
  });

  drawHorizontalBarChart(p1, {
    x: rightX,
    yTop: 612,
    w: chartW,
    h: chartH,
    title: "2. AAEF AGENT PERFORMANCE PROFILES",
    items: [
      { label: "Operational", value: data.aaefDistribution.OPERATIONAL ?? 0, rgb: "0.000 0.620 0.451" },
      { label: "Developing", value: data.aaefDistribution.DEVELOPING ?? 0, rgb: "0.000 0.447 0.698" },
      { label: "Restricted", value: data.aaefDistribution.RESTRICTED ?? 0, rgb: "0.902 0.624 0.000" },
      { label: "Under Review", value: data.aaefDistribution.UNDER_REVIEW ?? 0, rgb: "0.835 0.369 0.000" },
    ],
  });

  drawHorizontalBarChart(p1, {
    x: leftX,
    yTop: 450,
    w: chartW,
    h: chartH,
    title: "3. AUTONOMY LEVEL DISTRIBUTION",
    items: [
      { label: "Assistive", value: data.autonomyCounts.ASSISTIVE ?? 0, rgb: "0.337 0.706 0.914" },
      { label: "Human-in-Loop", value: data.autonomyCounts.HUMAN_IN_THE_LOOP ?? 0, rgb: "0.000 0.447 0.698" },
      { label: "Human-on-Loop", value: data.autonomyCounts.HUMAN_ON_THE_LOOP ?? 0, rgb: "0.902 0.624 0.000" },
      { label: "Autonomous", value: data.autonomyCounts.AUTONOMOUS ?? 0, rgb: "0.800 0.475 0.655" },
    ],
  });

  drawHorizontalBarChart(p1, {
    x: rightX,
    yTop: 450,
    w: chartW,
    h: chartH,
    title: "4. VALUE REALISATION & EXPOSURE (SGD)",
    items: [
      {
        label: "Measured",
        value: data.measuredBenefitSgd,
        displayValue: formatCompactCurrency(data.measuredBenefitSgd),
        rgb: "0.000 0.620 0.451",
      },
      {
        label: "Est / Assumed",
        value: data.assumedOrEstimatedSgd,
        displayValue: formatCompactCurrency(data.assumedOrEstimatedSgd),
        rgb: "0.337 0.706 0.914",
      },
      {
        label: "Total TCO",
        value: data.totalCostSgd,
        displayValue: formatCompactCurrency(data.totalCostSgd),
        rgb: "0.45 0.52 0.60",
      },
      {
        label: "Value-at-Risk",
        value: data.valueAtRiskSgd,
        displayValue: formatCompactCurrency(-data.valueAtRiskSgd),
        rgb: "0.835 0.369 0.000",
      },
    ],
  });

  // Financial Summary Callout Box at bottom of Page 1
  p1.push("0.96 0.97 0.99 rg 36 210 523.28 74 re f");
  p1.push("0.86 0.89 0.93 RG 0.7 w 36 210 523.28 74 re S");
  p1.push("0.118 0.227 0.373 rg");
  p1.push("BT /F2 9.5 Tf 46 266 Td (5. PORTFOLIO FINANCIAL & VALUE SUMMARY (SGD)) Tj ET");
  p1.push("0.10 0.14 0.20 rg");
  p1.push(
    `BT /F2 8.5 Tf 46 248 Td (${escapePdfText(
      `Total Cost of Ownership: SGD ${data.totalCostSgd.toLocaleString()}   |   Net Benefit: SGD ${data.netBenefitSgd.toLocaleString()}   |   Headline ROI: ${data.roiPercent}%`,
    )}) Tj ET`,
  );
  p1.push(
    `BT /F1 8.5 Tf 46 232 Td (${escapePdfText(
      `Measured Benefit (Verified): SGD ${data.measuredBenefitSgd.toLocaleString()}   |   Estimated & Assumed: SGD ${data.assumedOrEstimatedSgd.toLocaleString()}`,
    )}) Tj ET`,
  );
  p1.push(
    `BT /F1 8.5 Tf 46 218 Td (${escapePdfText(
      `Linked Residual Value-at-Risk: -SGD ${data.valueAtRiskSgd.toLocaleString()}   |   Risk-Adjusted ROI: ${data.riskAdjustedRoiPercent}%`,
    )}) Tj ET`,
  );

  buildPageFooter(p1, 1, 2);

  // ---------------- PAGE 2: RISKS & INCIDENTS TABLES ----------------
  const p2: string[] = [];

  p2.push("0.094 0.184 0.310 rg 0 788 595.28 54 re f");
  p2.push("0.000 0.447 0.698 rg 0 785 595.28 3 re f");
  p2.push("1 1 1 rg");
  p2.push("BT /F2 12 Tf 36 812 Td (RISK POSTURE & INCIDENT REGISTER DETAILS) Tj ET");
  p2.push("0.82 0.89 0.96 rg");
  p2.push(
    `BT /F1 8.5 Tf 36 798 Td (${escapePdfText(
      `${data.organisationName} | ${data.generatedDate} | Appetite Breaches: ${data.appetiteBreachCount}`,
    )}) Tj ET`,
  );

  // Section 6: Top Risks Table
  let y = 760;
  p2.push("0.118 0.227 0.373 rg");
  p2.push(
    `BT /F2 10 Tf 36 ${y} Td (${escapePdfText(
      `6. TOP RISKS VERSUS APPETITE (${data.appetiteBreachCount} APPETITE BREACHES)`,
    )}) Tj ET`,
  );
  y -= 18;

  // Table header
  p2.push("0.93 0.95 0.98 rg 36 " + (y - 5) + " 523.28 18 re f");
  p2.push("0.15 0.20 0.28 rg");
  p2.push(`BT /F2 8 Tf 42 ${y} Td (RISK CODE) Tj ET`);
  p2.push(`BT /F2 8 Tf 105 ${y} Td (ASSET) Tj ET`);
  p2.push(`BT /F2 8 Tf 158 ${y} Td (SCORE) Tj ET`);
  p2.push(`BT /F2 8 Tf 202 ${y} Td (APPETITE STATUS) Tj ET`);
  p2.push(`BT /F2 8 Tf 295 ${y} Td (RISK TITLE) Tj ET`);
  y -= 20;

  if (data.topRisks.length === 0) {
    p2.push("0.35 0.40 0.48 rg");
    p2.push(`BT /F1 8.5 Tf 42 ${y} Td (No active risks in selected filter scope.) Tj ET`);
    y -= 20;
  } else {
    data.topRisks.slice(0, 12).forEach((r, idx) => {
      if (idx % 2 === 1) {
        p2.push(`0.98 0.99 1.00 rg 36 ${y - 5} 523.28 17 re f`);
      }
      p2.push("0.10 0.14 0.20 rg");
      p2.push(`BT /F2 8 Tf 42 ${y} Td (${escapePdfText(r.code)}) Tj ET`);
      p2.push(`BT /F1 8 Tf 105 ${y} Td (${escapePdfText(r.assetCode)}) Tj ET`);
      p2.push(`BT /F2 8 Tf 162 ${y} Td (${r.residualScore}) Tj ET`);
      p2.push(r.breached ? "0.80 0.18 0.15 rg" : "0.000 0.550 0.380 rg");
      p2.push(`BT /F2 8 Tf 202 ${y} Td (${r.breached ? "BREACH" : "WITHIN APPETITE"}) Tj ET`);
      p2.push("0.15 0.20 0.28 rg");
      p2.push(`BT /F1 8 Tf 295 ${y} Td (${escapePdfText(r.title.slice(0, 52))}) Tj ET`);
      y -= 18;
    });
  }

  // Section 7: Recent Incidents Table
  y -= 18;
  p2.push("0.118 0.227 0.373 rg");
  p2.push(`BT /F2 10 Tf 36 ${y} Td (7. RECENT INCIDENTS & NEAR MISSES) Tj ET`);
  y -= 18;

  p2.push("0.93 0.95 0.98 rg 36 " + (y - 5) + " 523.28 18 re f");
  p2.push("0.15 0.20 0.28 rg");
  p2.push(`BT /F2 8 Tf 42 ${y} Td (INCIDENT) Tj ET`);
  p2.push(`BT /F2 8 Tf 105 ${y} Td (ASSET) Tj ET`);
  p2.push(`BT /F2 8 Tf 158 ${y} Td (SEVERITY) Tj ET`);
  p2.push(`BT /F2 8 Tf 222 ${y} Td (DATE) Tj ET`);
  p2.push(`BT /F2 8 Tf 295 ${y} Td (DESCRIPTION) Tj ET`);
  y -= 20;

  if (data.recentIncidents.length === 0) {
    p2.push("0.35 0.40 0.48 rg");
    p2.push(`BT /F1 8.5 Tf 42 ${y} Td (No recent incidents recorded in selected filter scope.) Tj ET`);
  } else {
    data.recentIncidents.slice(0, 10).forEach((inc, idx) => {
      if (idx % 2 === 1) {
        p2.push(`0.98 0.99 1.00 rg 36 ${y - 5} 523.28 17 re f`);
      }
      p2.push("0.10 0.14 0.20 rg");
      p2.push(`BT /F2 8 Tf 42 ${y} Td (${escapePdfText(inc.code)}) Tj ET`);
      p2.push(`BT /F1 8 Tf 105 ${y} Td (${escapePdfText(inc.assetCode)}) Tj ET`);
      const sevRgb =
        inc.severity === "CRITICAL" || inc.severity === "HIGH"
          ? "0.80 0.18 0.15"
          : inc.severity === "MEDIUM"
            ? "0.85 0.48 0.00"
            : "0.25 0.35 0.45";
      p2.push(`${sevRgb} rg`);
      p2.push(`BT /F2 8 Tf 158 ${y} Td (${escapePdfText(inc.severity)}) Tj ET`);
      p2.push("0.20 0.25 0.33 rg");
      p2.push(`BT /F1 8 Tf 222 ${y} Td (${escapePdfText(inc.date)}) Tj ET`);
      p2.push(`BT /F1 8 Tf 295 ${y} Td (${escapePdfText(inc.title.slice(0, 52))}) Tj ET`);
      y -= 18;
    });
  }

  buildPageFooter(p2, 2, 2);

  const p1Stream = p1.join("\n");
  const p2Stream = p2.join("\n");

  const objects: string[] = [
    "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj",
    "2 0 obj\n<< /Type /Pages /Kids [3 0 R 4 0 R] /Count 2 >>\nendobj",
    "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595.28 841.89] /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> /Contents 7 0 R >>\nendobj",
    "4 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595.28 841.89] /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> /Contents 8 0 R >>\nendobj",
    "5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj",
    "6 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\nendobj",
    `7 0 obj\n<< /Length ${Buffer.byteLength(p1Stream, "utf-8")} >>\nstream\n${p1Stream}\nendstream\nendobj`,
    `8 0 obj\n<< /Length ${Buffer.byteLength(p2Stream, "utf-8")} >>\nstream\n${p2Stream}\nendstream\nendobj`,
  ];

  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [0];

  for (const obj of objects) {
    offsets.push(Buffer.byteLength(pdf, "utf-8"));
    pdf += `${obj}\n`;
  }

  const xrefStart = Buffer.byteLength(pdf, "utf-8");
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += "0000000000 65535 f \n";
  for (let i = 1; i <= objects.length; i++) {
    pdf += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
  }

  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;

  return Buffer.from(pdf, "utf-8");
}
